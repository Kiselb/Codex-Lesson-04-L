const LABELS = {
  budget: 'бюджет', shoeType: 'обувь', style: 'стиль', color: 'цвет', material: 'материал', urgency: 'срок', name: 'имя',
};

function extractPreferences(text) {
  const value = String(text).trim();
  const lower = value.toLowerCase();
  const result = {};
  const name = value.match(/(?:меня зовут|мо[её] имя)\s+([А-ЯЁA-Z][а-яёa-z-]{1,30})/i);
  const budget = value.match(/(?:бюджет|до|не дороже)\s*(\d[\d\s]*(?:[.,]\d+)?)\s*(₽|руб(?:лей|ля|ль)?|\$|доллар(?:ов|а)?|€|евро)?/i);
  if (name) result.name = name[1];
  if (budget) result.budget = `${budget[1].replace(/\s/g, '')} ${budget[2] || '₽'}`;
  const colors = ['чёрн', 'черн', 'бел', 'красн', 'син', 'зелён', 'зелен', 'жёлт', 'желт', 'розов', 'фиолет', 'золот', 'серебр', 'оранж'];
  const color = colors.find((part) => lower.includes(part));
  if (color) result.color = ({ 'чёрн': 'чёрный', черн: 'чёрный', бел: 'белый', красн: 'красный', син: 'синий', 'зелён': 'зелёный', зелен: 'зелёный', 'жёлт': 'жёлтый', желт: 'жёлтый', розов: 'розовый', фиолет: 'фиолетовый', золот: 'золотой', серебр: 'серебряный', оранж: 'оранжевый' })[color];
  const styles = [['кибер', 'киберпанк'], ['гламур', 'гламурный'], ['класс', 'классический'], ['спорт', 'спортивный'], ['премиум', 'премиум'], ['молод', 'молодёжный'], ['эксклюз', 'эксклюзивный']];
  const style = styles.find(([part]) => lower.includes(part));
  if (style) result.style = style[1];
  const shoes = [['кроссов', 'кроссовки'], ['ботин', 'ботинки'], ['кед', 'кеды'], ['туф', 'туфли'], ['сапог', 'сапоги'], ['детск', 'детская обувь'], ['сценическ', 'сценическая обувь'], ['поход', 'походная обувь']];
  const shoe = shoes.find(([part]) => lower.includes(part));
  if (shoe) result.shoeType = shoe[1];
  const materials = [['кож', 'кожа'], ['шёлк', 'шёлк'], ['шелк', 'шёлк'], ['кевлар', 'кевлар'], ['хлоп', 'хлопок'], ['светоотраж', 'светоотражающий материал'], ['золот', 'золото'], ['серебр', 'серебро']];
  const material = materials.find(([part]) => lower.includes(part));
  if (material) result.material = material[1];
  if (/срочно|сегодня|как можно быстрее/.test(lower)) result.urgency = 'срочно';
  else if (/48\s*час|два дня/.test(lower)) result.urgency = 'до 48 часов';
  else if (/72\s*час|три дня/.test(lower)) result.urgency = 'до 72 часов';
  result.lastRequest = value.slice(0, 240);
  return result;
}

function memorySummary(memory) {
  return Object.entries(memory || {})
    .filter(([key, value]) => value && key !== 'lastRequest')
    .map(([key, value]) => `${LABELS[key] || key}: ${value}`)
    .join(', ');
}

function reply({ text, memory, history = [] }) {
  const lower = String(text).toLowerCase();
  const known = memorySummary(memory);
  const intro = memory.name ? `${memory.name}, ` : '';
  if (/чуж|другого пользовател|все пользовател|админ|парол|баз[ау] данных|json/.test(lower)) {
    return `${intro}я могу работать только с вашим профилем и не раскрываю данные других клиентов или функции администратора.`;
  }
  if (/что (?:ты |вы )?(?:знаете|знаешь|помните|помнишь)|мои предпочтения|покажи.*данн/.test(lower)) {
    return known ? `Вот что я помню о ваших предпочтениях: ${known}. Вы можете изменить или удалить эти сведения в разделе «Мои данные».` : 'Пока у меня нет сохранённых предпочтений. Расскажите, для какой обуви нужны шнурки, какой стиль и бюджет вам подходят.';
  }
  if (/дорог|цена|стоим|бюджет/.test(lower)) {
    return `${intro}серийные шнурки стоят до $5 за пару, заказные — до 10% стоимости обуви, эксклюзивные рассчитываются индивидуально. ${memory.budget ? `Учту ваш бюджет ${memory.budget}.` : 'Какой бюджет вам удобен?'}`;
  }
  if (/срочно|быстр|срок|достав/.test(lower)) {
    return `${intro}каталожные модели доставляем за 48 часов, заказные и эксклюзивные изготавливаем за 72 часа. ${memory.shoeType ? `Для варианта «${memory.shoeType}» могу подобрать оптимальный путь.` : 'Подскажите тип обуви.'}`;
  }
  if (/гарант|качеств|не понрав/.test(lower)) {
    return `${intro}на серийные модели действует гарантия 2 года, на заказные — 10 лет, на эксклюзивные — пожизненная при соблюдении правил эксплуатации. Если результат не понравится, мы вернём деньги.`;
  }
  if (/ремонт|порвал|сломал|эглет|наконечник/.test(lower)) {
    return `${intro}мы ремонтируем премиальные и эксклюзивные шнурки, включая замену или апгрейд эглетов. Что произошло и к какой категории относятся шнурки?`;
  }
  if (/утилиз|выброс|старые/.test(lower)) {
    return `${intro}примем старые шнурки на экологичную утилизацию. Сообщите ваш город — менеджер предложит удобный способ передачи.`;
  }
  if (/привет|здравств|добрый/.test(lower) && history.length <= 2) {
    return known ? `Добрый день${memory.name ? `, ${memory.name}` : ''}! Рад снова вас видеть. Помню: ${known}. Продолжим подбор или начнём новый заказ?` : 'Добрый день! Я консультант компании «Шальные Шнурки». Подберём модель из каталога, создадим шнурки на заказ или обсудим ремонт?';
  }
  if (memory.shoeType || memory.style || memory.color) {
    const details = [memory.color, memory.style, memory.shoeType && `для ${memory.shoeType}`].filter(Boolean).join(', ');
    return `${intro}предлагаю ${details || 'индивидуальный вариант'}. ${memory.urgency === 'срочно' ? 'Если важна скорость, начнём с каталога с доставкой за 48 часов.' : 'Можно выбрать каталог до $5 или индивидуальное изготовление за 72 часа.'} ${!memory.budget ? 'Какой бюджет заложили?' : `Ориентир по бюджету ${memory.budget} учёл.`}`;
  }
  return `${intro}расскажите, для какой обуви нужны шнурки и что важнее: стиль, прочность, влагостойкость или необычный дизайн? Можно также назвать цвет и бюджет.`;
}

module.exports = { extractPreferences, memorySummary, reply };
